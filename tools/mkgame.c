/* mkgame.c -- writes game/game.toml for the disc the user supplies.
 *
 * Everything in the declaration is read from the disc itself (IP.BIN header and
 * the ISO9660 root directory), so nothing from the game is stored in this
 * repository. Uses SaturnRecomp's own disc layer, so if this tool can read the
 * disc, the runtime can too.
 *
 *   mkgame <disc to open> <disc path for toml> <bios path for toml> <out.toml>
 *
 * The two "for toml" paths are written verbatim; relative ones are resolved by
 * the runtime against the directory holding game.toml.
 */
#include "disc.h"
#include <stdio.h>
#include <string.h>

static void toml_string(FILE *f, const char *s)
{
    /* SaturnRecomp's parser takes the text between the quotes literally, so
     * only characters that would end the string or the line are dropped. */
    for (; *s; s++)
        if (*s != '"' && (unsigned char)*s >= 32) fputc(*s, f);
}

int main(int argc, char **argv)
{
    disc d;
    iso_fs fs;
    saturn_ip ip;
    const iso_entry *boot = NULL;
    uint32_t load;
    FILE *out;
    int naudio = 0;

    if (argc != 5) {
        fputs("usage: mkgame <disc> <disc-path-for-toml> <bios-path-for-toml> <out.toml>\n", stderr);
        return 2;
    }
    memset(&fs, 0, sizeof fs);
    if (disc_open(&d, argv[1]) != 0) {
        fprintf(stderr, "error: cannot open disc: %s\n", d.err);
        return 1;
    }
    if (ip_read(&d, &ip) != 0) {
        fputs("error: not a Sega Saturn disc (no SEGA SEGASATURN header)\n", stderr);
        disc_close(&d);
        return 1;
    }
    if (iso_read(&d, &fs) != 0) {
        fprintf(stderr, "error: cannot read ISO9660 filesystem: %s\n", d.err);
        disc_close(&d);
        return 1;
    }
    /* The IPL loads the first file of the root directory, in directory order. */
    for (int i = 0; i < fs.nentries; i++)
        if (!fs.entries[i].is_dir && !strchr(fs.entries[i].path + 1, '/')) {
            boot = &fs.entries[i];
            break;
        }
    if (!boot) {
        fputs("error: no file in the ISO9660 root directory\n", stderr);
        iso_free(&fs);
        disc_close(&d);
        return 1;
    }
    for (int i = 0; i < d.ntracks; i++)
        if (d.tracks[i].mode == TRACK_AUDIO) naudio++;

    load = ip.first_read_addr ? ip.first_read_addr : 0x06004000u;

    printf("title        %s\n", ip.title);
    printf("product      %s %s\n", ip.product_no, ip.version);
    printf("area         %s\n", ip.area);
    printf("peripherals  %s\n", ip.peripherals);
    printf("tracks       %d (%d audio)\n", d.ntracks, naudio);
    printf("first read   %s -> 0x%08X\n", boot->path, load);

    out = fopen(argv[4], "wb");
    if (!out) {
        fprintf(stderr, "error: cannot write %s\n", argv[4]);
        iso_free(&fs);
        disc_close(&d);
        return 1;
    }
    fputs("# Generated by tools/mkgame.c from the user's own disc. Do not commit.\n\n", out);
    fputs("[game]\nname       = \"", out);       toml_string(out, ip.title);
    fputs("\"\nprefix     = \"saturnbomberman\"\n", out);
    fputs("product_no = \"", out);                toml_string(out, ip.product_no);
    fputs("\"\ndisc       = \"", out);            toml_string(out, argv[2]);
    fputs("\"\nbios       = \"", out);            toml_string(out, argv[3]);
    fputs("\"\n\n[[module]]\nname        = \"main\"\nfile        = \"", out);
    toml_string(out, boot->path);
    fprintf(out, "\"\ncpu         = \"sh2\"\ncompression = \"none\"\n"
                 "load_addr   = 0x%08X\nentry       = 0x%08X\nfirst_read  = true\n",
            load, load);
    if (fclose(out) != 0) {
        fprintf(stderr, "error: write failed: %s\n", argv[4]);
        iso_free(&fs);
        disc_close(&d);
        return 1;
    }
    printf("wrote        %s\n", argv[4]);
    iso_free(&fs);
    disc_close(&d);
    return 0;
}
